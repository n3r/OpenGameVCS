#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC = resolve(ROOT, '../../../spec/selective-sync/v1');
const CHECK = process.argv.length === 3 && process.argv[2] === '--check';
if (process.argv.length > (CHECK ? 3 : 2)) throw new Error('usage: node scripts/sync-contract.mjs [--check]');

const EXPECTED_MANIFEST_SHA256 = '4b4abe57a73f5e04dec184965a7d08130d5b311a6c745cc0dfb7728432fbc6dc';
const EXPECTED_ARTIFACT_SET_SHA256 = 'bd43f2898b07d3545e1d3922d5a18632fb6d1fe95617d628b99a26aee184652b';
const EXPECTED_PATH_MANIFEST_SHA256 = '2f343e1dac238da527fbd36160419ec6fb53b780ac7e33c01e11acabbdd4782b';
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const manifestBytes = await readFile(resolve(SPEC, 'manifest.json'));
if (sha256(manifestBytes) !== EXPECTED_MANIFEST_SHA256) throw new Error('selective-sync contract manifest differs from the pinned Rust binding');
const manifest = JSON.parse(manifestBytes);
if (manifest.schemaVersion !== 'ogvcs.selective-sync/contract-manifest/v1'
    || manifest.contractVersion !== '0.1.0-rc.1'
    || manifest.state !== 'private-untrusted-selection-candidate'
    || manifest.artifactSetSha256 !== EXPECTED_ARTIFACT_SET_SHA256
    || manifest.predecessorPins?.path?.manifestSha256 !== EXPECTED_PATH_MANIFEST_SHA256
    || manifest.counts?.artifacts !== 13 || manifest.counts?.errors !== 32
    || manifest.counts?.goldenCases !== 3 || manifest.networkRoutes?.length !== 0
    || Object.values(manifest.publicClaims ?? {}).some((value) => value !== false)) {
  throw new Error('selective-sync contract assignments differ from the pinned Rust binding');
}
for (const artifact of manifest.artifacts) {
  const bytes = await readFile(resolve(SPEC, artifact.path));
  if (bytes.length !== artifact.bytes || sha256(bytes) !== artifact.sha256) throw new Error(`${artifact.path}: differs from the authenticated selective-sync manifest`);
}
const contract = JSON.parse(await readFile(resolve(SPEC, 'contract.json')));
const expectedLimits = {
  collisionKeyBytesMaximum: 32_768, collisionKeyBytesTotalMaximum: 67_108_864,
  compiledRuleBytesMaximum: 16_777_216, fullLogicalBytesMaximum: 9_007_199_254_740_991,
  inputRecordBytesMaximum: 4_185, logicalBytesMaximum: 1_099_511_627_776,
  metadataBytesMaximum: 67_108_864, metadataRecordsMaximum: 100_000,
  outputBytesMaximum: 75_497_472, outputRecordBytesMaximum: 4_154,
  ruleBytesMaximum: 4_114, rulesMaximum: 4_096, sinkFragmentBytesMaximum: 4_154,
};
if (JSON.stringify(contract.limits) !== JSON.stringify(expectedLimits)
    || contract.output?.entryDigest !== 'input-only-opaque-metadata-record-commitment-never-emitted'
    || contract.output?.sinkSemantics !== 'synchronous-fragment-emission-has-no-application-value;-javascript-callback-write-and-flush-return-undefined;-rust-write-all-and-flush-complete-with-ok-unit;-each-javascript-call-receives-a-private-fragment-copy'
    || contract.output?.errorDisposition !== 'discard-all-sink-bytes-no-summary') throw new Error('selective-sync limits or output trust boundary drifted');
const artifact = (path) => manifest.artifacts.find((entry) => entry.path === path);
const golden = artifact('vectors/golden.json'); const errors = artifact('registries/errors.json');
if (!golden || !errors) throw new Error('selective-sync vector/error authority is missing');
const rustString = (value) => JSON.stringify(value);
const rustDigest = (name, value) => `pub const ${name}: &str =\n    ${rustString(value)};\n`;
const generated = `// Generated by scripts/sync-contract.mjs from the authenticated OGVCS-013 rc.1 authority.\n`
  + `// Contract manifest SHA-256: ${EXPECTED_MANIFEST_SHA256}\n\n`
  + `pub const CONTRACT_VERSION: &str = ${rustString(manifest.contractVersion)};\n`
  + rustDigest('CONTRACT_MANIFEST_SHA256', EXPECTED_MANIFEST_SHA256)
  + rustDigest('CONTRACT_ARTIFACT_SET_SHA256', EXPECTED_ARTIFACT_SET_SHA256)
  + rustDigest('PATH_CONTRACT_MANIFEST_SHA256', EXPECTED_PATH_MANIFEST_SHA256)
  + rustDigest('ERROR_REGISTRY_SHA256', errors.sha256)
  + rustDigest('GOLDEN_VECTORS_SHA256', golden.sha256);
const outputs = [
  ['src/generated_contract.rs', Buffer.from(generated)],
  ['tests/errors.json', await readFile(resolve(SPEC, 'registries/errors.json'))],
  ['tests/golden.json', await readFile(resolve(SPEC, 'vectors/golden.json'))],
];
let changed = false;
for (const [path, expected] of outputs) {
  const destination = resolve(ROOT, path);
  if (CHECK) {
    const actual = await readFile(destination).catch(() => null);
    if (actual === null || !actual.equals(expected)) { process.stderr.write(`${path}: generated content differs\n`); changed = true; }
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, expected);
  }
}
if (changed) process.exitCode = 1;
