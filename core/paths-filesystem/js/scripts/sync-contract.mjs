#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC = resolve(ROOT, '../../../spec/path-filesystem/v1');
const CHECK = process.argv.slice(2).includes('--check');
if (process.argv.length > 3 || (process.argv.length === 3 && !CHECK)) {
  throw new Error('usage: node scripts/sync-contract.mjs [--check]');
}

const manifestBytes = await readFile(resolve(SPEC, 'manifest.json'));
const manifest = JSON.parse(manifestBytes);
const profiles = JSON.parse(await readFile(resolve(SPEC, 'registries/platform-profiles.json'), 'utf8'));
const errors = JSON.parse(await readFile(resolve(SPEC, 'registries/errors.json'), 'utf8'));
const generated = `// Generated by scripts/sync-contract.mjs; do not edit.\n`
  + `export const CONTRACT_VERSION = ${JSON.stringify(manifest.contractVersion)};\n`
  + `export const CONTRACT_MANIFEST_SHA256 = ${JSON.stringify((await import('node:crypto')).createHash('sha256').update(manifestBytes).digest('hex'))};\n`
  + `export const REGISTRY_SET_SHA256 = ${JSON.stringify(manifest.registrySetSha256)};\n`
  + `export const UNICODE_CASE_FOLDING_SHA256 = ${JSON.stringify(manifest.unicode.caseFoldingSha256)};\n`
  + `export const PLATFORM_PROFILES = Object.freeze(${JSON.stringify(profiles.entries)});\n`
  + `export const ERROR_ENTRIES = Object.freeze(${JSON.stringify(errors.entries)});\n`;
const destination = resolve(ROOT, 'src/generated-contract.mjs');
if (CHECK) {
  const actual = await readFile(destination, 'utf8').catch(() => null);
  if (actual !== generated) {
    process.stderr.write('src/generated-contract.mjs: generated content differs\n');
    process.exitCode = 1;
  }
} else {
  await writeFile(destination, generated, 'utf8');
}
