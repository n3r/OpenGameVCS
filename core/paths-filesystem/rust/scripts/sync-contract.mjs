#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC = resolve(ROOT, '../../../spec/path-filesystem/v1');
const CHECK = process.argv.slice(2).includes('--check');
if (process.argv.length > 3 || (process.argv.length === 3 && !CHECK)) {
  throw new Error('usage: node scripts/sync-contract.mjs [--check]');
}

const EXPECTED_MANIFEST_SHA256 = '2f343e1dac238da527fbd36160419ec6fb53b780ac7e33c01e11acabbdd4782b';
const EXPECTED_CASE_FOLDING_SHA256 = '6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb';
const EXPECTED_REGISTRY_SET_SHA256 = 'bbabdd95d78cfe0dd9751ab67ccbd9dfa5565bf8c049468aea3129bec787bd42';
const EXPECTED_VECTOR_SET_SHA256 = '1eca9694940f23cbf9137044c64344a52483a7fe0fb6875d35348e2e94a52cf0';
const EXPECTED_MAPPING_COUNT = 1_557;

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const manifestBytes = await readFile(resolve(SPEC, 'manifest.json'));
if (sha256(manifestBytes) !== EXPECTED_MANIFEST_SHA256) {
  throw new Error('path contract manifest differs from the pinned OGVCS-004 authority');
}
const manifest = JSON.parse(manifestBytes);
if (manifest.schemaVersion !== 'ogvcs.path/contract-manifest/v1'
    || manifest.contractVersion !== '1.0.0'
    || manifest.unicode?.version !== '16.0.0'
    || manifest.unicode?.mapping !== 'full-default-C-and-F-without-T-or-post-fold-normalization'
    || manifest.unicode?.caseFoldingSha256 !== EXPECTED_CASE_FOLDING_SHA256
    || manifest.registrySetSha256 !== EXPECTED_REGISTRY_SET_SHA256
    || manifest.vectorSetSha256 !== EXPECTED_VECTOR_SET_SHA256
    || manifest.counts?.profiles !== 4
    || manifest.counts?.foldCases !== 7
    || manifest.counts?.pathCases !== 25
    || manifest.counts?.collisionCases !== 7) {
  throw new Error('path contract manifest assignments differ from the pinned Rust binding');
}

for (const record of manifest.artifacts) {
  const bytes = await readFile(resolve(SPEC, record.path));
  if (bytes.length !== record.bytes || sha256(bytes) !== record.sha256) {
    throw new Error(`${record.path}: does not match the authenticated path manifest`);
  }
}

const tableBytes = await readFile(resolve(SPEC, 'data/CaseFolding-16.0.0.txt'));
if (sha256(tableBytes) !== EXPECTED_CASE_FOLDING_SHA256) {
  throw new Error('Unicode case-folding table differs from the pinned OGVCS-004 authority');
}
const mappings = [];
for (const line of tableBytes.toString('utf8').split('\n')) {
  const body = line.split('#', 1)[0].trim();
  if (!body) continue;
  const match = /^([0-9A-F]{4,6});\s*([CFST]);\s*([0-9A-F ]+);$/u.exec(body);
  if (!match) throw new Error(`malformed CaseFolding-16.0.0 line: ${line}`);
  if (match[2] !== 'C' && match[2] !== 'F') continue;
  const source = Number.parseInt(match[1], 16);
  const target = match[3].trim().split(/ +/u).map((part) => Number.parseInt(part, 16));
  if (source > 0x10ffff || (source >= 0xd800 && source <= 0xdfff)
      || target.some((scalar) => scalar > 0x10ffff || (scalar >= 0xd800 && scalar <= 0xdfff))
      || (mappings.length > 0 && mappings.at(-1).source >= source)) {
    throw new Error('CaseFolding-16.0.0 C/F mappings are not strict Unicode scalars in source order');
  }
  mappings.push({ source, target });
}
if (mappings.length !== EXPECTED_MAPPING_COUNT) {
  throw new Error('Unicode 16 C/F mapping count differs from the pinned OGVCS-004 authority');
}

const readJson = async (relative) => JSON.parse(await readFile(resolve(SPEC, relative), 'utf8'));
const profileRegistry = await readJson('registries/platform-profiles.json');
const profiles = profileRegistry.entries;
if (profileRegistry.schemaVersion !== 'ogvcs.path/registry/v1'
    || profileRegistry.registry !== 'platform-profiles'
    || profiles.length !== 4
    || profiles.some((profile, index) => profile.code !== index + 1
      || profile.owner !== 'OGVCS-004' || profile.state !== 'ratified'
      || profile.limits.depth !== 256 || profile.limits.joinedUtf8Bytes !== 4096
      || profile.limits.joinedUtf16Units !== 4096 || profile.limits.segmentUtf8Bytes !== 255
      || profile.limits.segmentUtf16Units !== 255)) {
  throw new Error('platform profile registry differs from the four ratified v1 assignments');
}

const rustString = (value) => JSON.stringify(value);
const generated = `// Generated by scripts/sync-contract.mjs from the authenticated OGVCS-004 authority.\n`
  + `// Unicode-DFS-2016 applies to the table; see unicode/UNICODE-LICENSE.txt.\n`
  + `// Contract manifest SHA-256: ${EXPECTED_MANIFEST_SHA256}\n\n`
  + `pub const CONTRACT_VERSION: &str = ${rustString(manifest.contractVersion)};\n`
  + `pub const CONTRACT_MANIFEST_SHA256: &str = ${rustString(EXPECTED_MANIFEST_SHA256)};\n`
  + `pub const REGISTRY_SET_SHA256: &str = ${rustString(EXPECTED_REGISTRY_SET_SHA256)};\n`
  + `pub const VECTOR_SET_SHA256: &str = ${rustString(EXPECTED_VECTOR_SET_SHA256)};\n`
  + `pub const UNICODE_VERSION: &str = ${rustString(manifest.unicode.version)};\n`
  + `pub const UNICODE_CASE_FOLDING_SHA256: &str = ${rustString(EXPECTED_CASE_FOLDING_SHA256)};\n`
  + `pub const UNICODE_CASE_FOLDING_MAPPING_COUNT: usize = ${EXPECTED_MAPPING_COUNT};\n\n`
  + `pub(crate) const GENERATED_PROFILES: &[GeneratedProfile] = &[\n`
  + profiles.map((profile) => `    GeneratedProfile { reference: ${rustString(profile.profile)}, code: ${profile.code}, platform_case_fold: ${profile.rules.platformCaseFold}, windows_names: ${profile.rules.windowsNames}, macos_colon: ${profile.rules.macosColon}, depth: ${profile.limits.depth}, joined_utf8_bytes: ${profile.limits.joinedUtf8Bytes}, joined_utf16_units: ${profile.limits.joinedUtf16Units}, segment_utf8_bytes: ${profile.limits.segmentUtf8Bytes}, segment_utf16_units: ${profile.limits.segmentUtf16Units} },`).join('\n')
  + `\n];\n\n`
  + `pub(crate) const CASE_FOLDING: &[(u32, &[u32])] = &[\n`
  + mappings.map(({ source, target }) => `    (0x${source.toString(16)}, &[${target.map((scalar) => `0x${scalar.toString(16)}`).join(', ')}]),`).join('\n')
  + `\n];\n`;

const outputs = [
  ['src/generated_contract.rs', Buffer.from(generated, 'utf8')],
  ['tests/fold-cases.json', await readFile(resolve(SPEC, 'vectors/fold-cases.json'))],
  ['tests/path-cases.json', await readFile(resolve(SPEC, 'vectors/path-cases.json'))],
  ['tests/collision-cases.json', await readFile(resolve(SPEC, 'vectors/collision-cases.json'))],
  ['unicode/UNICODE-LICENSE.txt', await readFile(resolve(SPEC, 'data/UNICODE-LICENSE.txt'))],
  ['THIRD_PARTY_NOTICES.md', await readFile(resolve(SPEC, 'THIRD_PARTY_NOTICES.md'))],
];
let changed = false;
for (const [relative, expected] of outputs) {
  const destination = resolve(ROOT, relative);
  if (CHECK) {
    const actual = await readFile(destination).catch(() => null);
    if (actual === null || !actual.equals(expected)) {
      process.stderr.write(`${relative}: generated content differs\n`);
      changed = true;
    }
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, expected);
  }
}
if (changed) process.exitCode = 1;
