#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC = resolve(ROOT, '../../../spec/cli-workspace/v1');
const CHECK = process.argv.slice(2).includes('--check');
if (process.argv.length > 3 || (process.argv.length === 3 && !CHECK)) {
  throw new Error('usage: node scripts/sync-contract.mjs [--check]');
}

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const canonicalBytes = (value) => Buffer.from(`${JSON.stringify(value)}\n`, 'utf8');
const manifestBytes = await readFile(resolve(SPEC, 'manifest.json'));
const manifest = JSON.parse(manifestBytes);
for (const record of manifest.artifacts) {
  const bytes = await readFile(resolve(SPEC, record.path));
  if (bytes.length !== record.bytes || sha256(bytes) !== record.sha256) {
    throw new Error(`${record.path}: does not match contract manifest`);
  }
}
if (sha256(canonicalBytes(manifest.artifacts)) !== manifest.artifactSetSha256) {
  throw new Error('contract artifact set digest does not match manifest');
}

const readJson = async (relative) => JSON.parse(await readFile(resolve(SPEC, relative), 'utf8'));
const schemaConst = async (relative) => (await readJson(relative)).properties.schema.const;
const exitRegistry = await readJson('registries/exit-classes.json');
const vectorBytes = await readFile(resolve(SPEC, 'vectors/contract-v1.json'));
const manifestSha256 = sha256(manifestBytes);
const rustString = (value) => JSON.stringify(value);
const exitName = (name) => name.replaceAll('-', '_').toUpperCase();
const generated = `// Generated by scripts/sync-contract.mjs from the authenticated companion manifest.\n`
  + `// Contract manifest SHA-256: ${manifestSha256}\n\n`
  + `pub const CONTRACT_VERSION: &str = ${rustString(manifest.contractVersion)};\n`
  + `pub const CONTRACT_MANIFEST_SHA256: &str =\n    ${rustString(manifestSha256)};\n`
  + `pub const CONTRACT_ARTIFACT_SET_SHA256: &str =\n    ${rustString(manifest.artifactSetSha256)};\n`
  + `pub const CONTRACT_VECTOR_SHA256: &str =\n    ${rustString(sha256(vectorBytes))};\n`
  + `pub const RESULT_SCHEMA: &str = ${rustString(await schemaConst('schemas/CliResult.schema.json'))};\n`
  + `pub const CONFIG_SCHEMA: &str = ${rustString(await schemaConst('schemas/ConfigResolution.schema.json'))};\n`
  + `pub const WORKSPACE_METADATA_SCHEMA: &str = ${rustString(await schemaConst('schemas/WorkspaceMetadata.schema.json'))};\n`
  + `pub const WORKSPACE_REPORT_SCHEMA: &str = ${rustString(await schemaConst('schemas/WorkspaceReport.schema.json'))};\n`
  + `pub const INITIALIZATION_SCHEMA: &str = ${rustString(await schemaConst('schemas/InitializationRecord.schema.json'))};\n`
  + `pub const DIAGNOSTIC_SCHEMA: &str = ${rustString(await schemaConst('schemas/DiagnosticPreview.schema.json'))};\n\n`
  + exitRegistry.classes.map(({ name, exitCode }) => `pub const EXIT_CODE_${exitName(name)}: i32 = ${exitCode};`).join('\n')
  + `\n\npub const EXIT_CLASS_CODES: &[(&str, i32)] = &[\n`
  + exitRegistry.classes.map(({ name, exitCode }) => `    (${rustString(name)}, ${exitCode}),`).join('\n')
  + `\n];\n`;

const outputs = [
  { path: resolve(ROOT, 'src/generated_contract.rs'), bytes: Buffer.from(generated, 'utf8') },
  { path: resolve(ROOT, 'tests/contract-v1.json'), bytes: vectorBytes },
];
let changed = false;
for (const output of outputs) {
  if (CHECK) {
    const actual = await readFile(output.path).catch(() => null);
    if (actual === null || !actual.equals(output.bytes)) {
      process.stderr.write(`${output.path.slice(ROOT.length + 1)}: generated content differs\n`);
      changed = true;
    }
  } else {
    await writeFile(output.path, output.bytes);
  }
}
if (changed) process.exitCode = 1;
